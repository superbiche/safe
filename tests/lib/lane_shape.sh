#!/usr/bin/env bash
# What the project lane's auditor entries answer, DERIVED FROM THE REAL ANSWERS (ticket 1884, review round 1).
#
# No hand-written description of an answer is the authority for it. tests/contract/lane_auditor.sh runs every real entry on fixtures that FILL
# every array (a hit, a block, a gap, a root of each outcome, a scanner of each status), computes from the answers the member paths and their
# types and, for the members that name a state (status, outcome, verdict, severity, kind, coverage, source), their values (lane_shape_derive), and holds the result to tests/lib/lane_auditor_shapes.json byte for byte. That file is GENERATED by the suite
# (`LANE_SHAPES_UPDATE=1 bash tests/contract/lane_auditor.sh` rewrites it, and nothing else does); it carries the member `generated_by`, and an
# edit by hand fails the suite's comparison, so a reader of the repository can tell it is the real entries' answer and not a description of them.
#
# A shape holds, per entry: `allowed` (every member path and type some real answer had) and `required` (the paths EVERY real answer had). An
# answer of a stand-in conforms when it is exactly one non-empty document with no member repeated (the core's `repeated-members`), holds every
# required path, and holds no path and no type that is not allowed. Paths name members only (`.identities[].advisories[].id`); an array's
# elements share a path, and the ecosystem names that key `.audit_totals.by_ecosystem` are data, not members (`*`). Under `.socket.raw` (the Socket tool's own output, copied) the walk stops: it is not the auditor's to define.

LANE_SHAPES_FILE="${LANE_SHAPES_FILE:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lane_auditor_shapes.json}"

# lane_shape_paths <file>: one "path<TAB>type" line per member path of the document, unique and sorted.
lane_shape_paths() {
  jq -r '
    def enum_path: test("\\.(status|outcome|verdict|severity|kind|coverage|source)$");
    def walk_paths($p):
      [[$p, type, (if type == "string" and ($p | enum_path) then . else "" end)]]
      + (if ($p | endswith(".socket.raw")) then []
         elif type == "object" then [to_entries[] | .key as $k | .value | walk_paths($p + "." + $k)] | add // []
         elif type == "array" then [.[] | walk_paths($p + "[]")] | add // []
         else [] end);
    walk_paths("") | map(.[0] |= sub("^\\.audit_totals\\.by_ecosystem\\.[^.]+"; ".audit_totals.by_ecosystem.*")) | unique | .[] | "\(.[0])\t\(.[1])\t\(.[2])"' "$1"
}

# lane_shape_derive <answer file>...: the shape (JSON) of a set of real answers: {"allowed": {path: [types]}, "required": {path: [types]}}.
lane_shape_derive() {
  local file
  for file in "$@"; do
    jq -c --rawfile paths <(lane_shape_paths "$file") -n '[$paths | split("\n")[] | select(length > 0) | split("\t") | {path: .[0], type: .[1], value: (.[2] // "")}]'
  done | jq -sc '
    . as $all
    | ([$all[] | .[]] | group_by(.path) | map({key: .[0].path, value: ([.[].type] | unique)}) | from_entries) as $allowed
    | ([$all[] | .[] | select(.value != "")] | group_by(.path) | map({key: .[0].path, value: ([.[].value] | unique)}) | from_entries) as $values
    | ([$all[] | map(.path) | unique] | (.[0] // []) as $first | reduce .[1:][] as $set ($first; map(select(. as $p | $set | index($p))))) as $common
    | {allowed: $allowed, required: ([$common[] | {key: ., value: $allowed[.]}] | from_entries), values: $values}'
}

# lane_shape_check <entry> <answer file> [<core>]: prints one problem per line, returns 1 when the answer does not conform to the entry's shape.
lane_shape_check() {
  local entry="$1" file="$2" core="${3:-${LANE_SHAPE_CORE:-${SAFE_CORE_BIN:-}}}" problems="" paths repeated
  if [[ ! -s "$file" ]]; then
    printf '%s: the answer is empty (no bytes)\n' "$entry"
    return 1
  fi
  if ! jq -es 'length == 1' "$file" >/dev/null 2>&1; then
    printf '%s: the answer is not exactly one JSON document\n' "$entry"
    return 1
  fi
  if [[ -n "$core" && -x "$core" ]]; then
    repeated="$("$core" repeated-members <"$file" 2>/dev/null)" || true
    [[ "$repeated" == "[]" ]] || { printf '%s: a member is given more than once (%s)\n' "$entry" "${repeated:-the check could not run}"; return 1; }
  fi
  paths="$(lane_shape_paths "$file")" || { printf '%s: the answer cannot be read\n' "$entry"; return 1; }
  problems="$(jq -nr --arg entry "$entry" --rawfile paths <(printf '%s\n' "$paths") --slurpfile shapes "$LANE_SHAPES_FILE" '
    ($shapes[0][$entry]) as $shape
    | if $shape == null then ["no shape named \($entry)"] else
        ([$paths | split("\n")[] | select(length > 0) | split("\t") | {path: .[0], type: .[1], value: (.[2] // "")}]) as $got
        | ([$shape.required | to_entries[] | select(. as $r | ([$got[] | select(.path == $r.key)] | length) == 0) | "\($entry)\(.key): missing (every real answer has it)"])
          + ([$got[] | select(. as $g | ($shape.allowed[$g.path] // []) | index($g.type) | not)
              | if ($shape.allowed[.path] // null) == null then "\($entry)\(.path): a member no real answer has"
                else "\($entry)\(.path): is \(.type), a real answer has \($shape.allowed[.path] | join(" or "))" end])
          + ([$got[] | . as $g | select($g.value != "" and (($shape.values[$g.path] // []) | index($g.value) | not))
              | "\($entry)\($g.path): the value \"\($g.value)\" is none of those the real answers have (\(($shape.values[$g.path] // []) | join(", ")))"])
      end | .[]' 2>&1)" || problems="${problems:-the answer cannot be compared (the comparison itself failed)}"
  [[ -z "$problems" ]] || { printf '%s\n' "$problems"; return 1; }
}
