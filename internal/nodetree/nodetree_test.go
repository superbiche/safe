func TestPnpm(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, map[string]string{
		"package.json": `{"name":"app","dependencies":{"a":"1.0.0"}}`,
		"pnpm-lock.yaml": `---
lockfileVersion: '9.0'

importers:

  .:
    configDependencies: {}
    packageManagerDependencies:
      pnpm:
        specifier: ^11.20.0
        version: 11.26.0

packages:

  pnpm@11.26.0:
    resolution: {integrity: sha512-x}

snapshots:

  pnpm@11.26.0: {}
---
lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      a:
        specifier: 1.0.0
        version: 1.0.0(peer@2.0.0)

packages:

  a@1.0.0:
    resolution: {integrity: sha512-a}

  '@s/b@3.0.0':
    resolution: {integrity: sha512-b}

  peer@2.0.0:
    resolution: {integrity: sha512-p}

  '@esbuild/darwin-arm64@0.20.0':
    resolution: {integrity: sha512-d}
    cpu: [arm64]
    os: [darwin]

snapshots:

  a@1.0.0(peer@2.0.0):
    dependencies:
      '@s/b': 3.0.0
      peer: 2.0.0

  '@s/b@3.0.0': {}

  peer@2.0.0: {}

  '@esbuild/darwin-arm64@0.20.0':
    optional: true
`,
		"node_modules/a": "->.pnpm/a@1.0.0_peer@2.0.0/node_modules/a",
		"node_modules/.pnpm/a@1.0.0_peer@2.0.0/node_modules/a/package.json": pkg("a", "1.0.0"),
		"node_modules/.pnpm/a@1.0.0_peer@2.0.0/node_modules/@s/b":           "->../../../@s+b@3.0.0/node_modules/@s/b",
		"node_modules/.pnpm/a@1.0.0_peer@2.0.0/node_modules/peer":           "->../../peer@2.0.0/node_modules/peer",
		"node_modules/.pnpm/@s+b@3.0.0/node_modules/@s/b/package.json":      pkg("@s/b", "3.0.0"),
		"node_modules/.pnpm/peer@2.0.0/node_modules/peer/package.json":      pkg("peer", "2.0.0"),
		// An orphan pnpm has not pruned yet: nothing resolves to it.
		"node_modules/.pnpm/old@0.1.0/node_modules/old/package.json": pkg("old", "0.1.0"),
		"node_modules/.pnpm/node_modules/peer":                       "->../peer@2.0.0/node_modules/peer",
		"node_modules/.modules.yaml":                                 "layoutVersion: 5\n",
	})
	r := check(t, dir, "pnpm-lock.yaml")
	wantProblems(t, r)
	if r.Format != "pnpm" || r.Expected != 4 {
		t.Fatalf("format %q expected %d, want pnpm 4 (the env document is not the project's)", r.Format, r.Expected)
	}
	os.RemoveAll(filepath.Join(dir, "node_modules/.pnpm/peer@2.0.0"))
	wantProblems(t, check(t, dir, "pnpm-lock.yaml"), "missing peer@2.0.0")
}

func TestPnpmOlderKeys(t *testing.T) {
	for _, tc := range []struct{ key, name, version string }{
		{"/left-pad/1.3.0", "left-pad", "1.3.0"},
		{"/@scope/pkg/2.0.0_react@18.0.0", "@scope/pkg", "2.0.0"},
		{"/@scope/pkg@2.0.0(react@18.0.0)", "@scope/pkg", "2.0.0"},
		{"'@scope/pkg@2.0.0'", "@scope/pkg", "2.0.0"},
		{"left-pad@1.3.0", "left-pad", "1.3.0"},
	} {
		if n, v := pnpmKey(tc.key); n != tc.name || v != tc.version {
			t.Errorf("pnpmKey(%q) = %q %q, want %q %q", tc.key, n, v, tc.name, tc.version)
		}
	}
}

func TestBun(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, map[string]string{
		"package.json": `{"name":"app","dependencies":{"a":"^1.0.0"}}`,
		"bun.lock": `{
  "lockfileVersion": 1,
  "workspaces": {
    "": { "name": "app", "dependencies": { "a": "^1.0.0" }, },
  },
  "packages": {
    "a": ["a@1.0.0", "", { "dependencies": { "b": "^2.0.0" }, "optionalDependencies": { "wasm": "1.0.0" } }, "sha512-a"],
    "b": ["b@2.0.0", "", {}, "sha512-b"],
    "a/b": ["b@3.0.0", "", {}, "sha512-b3"],
    "wasm": ["wasm@1.0.0", "", { "cpu": "wasm32" }, "sha512-w"],
    "darwin": ["darwin@1.0.0", "", { "os": "darwin" }, "sha512-d"],
    "app-ws": ["app-ws@workspace:packages/ws"],
  },
}
`,
		"node_modules/a/package.json":                pkg("a", "1.0.0"),
		"node_modules/b/package.json":                pkg("b", "2.0.0"),
		"node_modules/a/node_modules/b/package.json": pkg("b", "3.0.0"),
	})
	r := check(t, dir, "bun.lock")
	// a/b@3.0.0 shadows the top-level b for a, so b@2.0.0 is required by
	// nothing — present here, and absent would be fine too.
	wantProblems(t, r)
	os.RemoveAll(filepath.Join(dir, "node_modules/a/node_modules"))
	wantProblems(t, check(t, dir, "bun.lock"), "missing b@3.0.0")
}

