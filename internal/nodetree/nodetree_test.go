func TestYarnClassic(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, map[string]string{
		"package.json": `{"dependencies":{"chokidar":"^2.0.0","left-pad":"^1.0.0"}}`,
		"yarn.lock": `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


chokidar@^2.0.0:
  version "2.1.8"
  resolved "https://registry.yarnpkg.com/chokidar/-/chokidar-2.1.8.tgz"
  dependencies:
    left-pad "^1.0.0"
  optionalDependencies:
    fsevents "^1.2.7"

fsevents@^1.2.7:
  version "1.2.13"
  dependencies:
    bindings "^1.5.0"
    nan "^2.12.1"

bindings@^1.5.0:
  version "1.5.0"

nan@^2.12.1:
  version "2.14.0"

"left-pad@^1.0.0", left-pad@^1.3.0:
  version "1.3.0"

"@scope/thing@npm:@real/thing@^2":
  version "2.0.0"
`,
		"node_modules/chokidar/package.json": pkg("chokidar", "2.1.8"),
		"node_modules/left-pad/package.json": pkg("left-pad", "1.3.0"),
		"node_modules/.yarn-integrity":       `{}`,
	})
	r := check(t, dir, "yarn.lock")
	// fsevents and the packages only it needs are optional on Linux; the
	// alias nothing in package.json reaches is not required either.
	wantProblems(t, r)
	if r.Format != "yarn-classic" {
		t.Fatalf("format %q", r.Format)
	}
	os.RemoveAll(filepath.Join(dir, "node_modules/left-pad"))
	wantProblems(t, check(t, dir, "yarn.lock"), "missing left-pad@1.3.0")
}

