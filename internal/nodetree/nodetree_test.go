func TestLinks(t *testing.T) {
	src, dst := t.TempDir(), t.TempDir()
	lock := `{"lockfileVersion":3,"packages":{"":{},"node_modules/ws":{"resolved":"packages/ws","link":true}}}`
	files := map[string]string{
		"package-lock.json":        lock,
		"packages/ws/package.json": pkg("ws", "1.0.0"),
		"node_modules/ws":          "->../packages/ws",
		// node-gyp's link to the system interpreter resolves the same anywhere.
		"node_modules/.bin/python3": "->/usr/bin/python3",
	}
	write(t, src, files)
	write(t, dst, map[string]string{"package-lock.json": lock, "packages/ws/package.json": pkg("ws", "1.0.0")})
	opts := Options{Lockfile: filepath.Join(dst, "package-lock.json"), Source: src, Target: dst, Modules: []string{"node_modules"}}
	r, err := Check(opts)
	if err != nil {
		t.Fatal(err)
	}
	wantProblems(t, r)

	write(t, src, map[string]string{
		"node_modules/.bin/escape": "->../../../elsewhere",
		"node_modules/.bin/source": "->" + filepath.Join(src, "packages/ws"),
		"node_modules/gone":        "->../packages/gone",
	})
	r, err = Check(opts)
	if err != nil {
		t.Fatal(err)
	}
	wantProblems(t, r,
		"symlink node_modules/.bin/escape -> ../../../elsewhere points outside the project",
		"symlink node_modules/.bin/source -> "+filepath.Join(src, "packages/ws")+" is absolute and points into a checkout",
		"symlink node_modules/gone -> ../packages/gone would dangle here (packages/gone is absent)",
	)
}

