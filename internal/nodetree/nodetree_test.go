// write creates files under dir from a path -> content map; a content
// starting with "->" makes a symlink to the rest.
func write(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if dest, ok := strings.CutPrefix(content, "->"); ok {
			if err := os.Symlink(dest, p); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func pkg(name, version string) string {
	return `{"name":"` + name + `","version":"` + version + `"}`
}

func check(t *testing.T, dir, lockfile string, modules ...string) Report {
	t.Helper()
	if len(modules) == 0 {
		modules = []string{"node_modules"}
	}
	r, err := Check(Options{Lockfile: filepath.Join(dir, lockfile), Source: dir, Target: dir, Modules: modules, Exclude: []string{".cache"}})
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	return r
}

func wantProblems(t *testing.T, r Report, want ...string) {
	t.Helper()
	if want == nil {
		want = []string{}
	}
	if !reflect.DeepEqual(r.Problems, want) {
		t.Fatalf("problems = %q, want %q", r.Problems, want)
	}
}

