// write creates files under dir from a path -> content map; a content
// starting with "->" makes a symlink to the rest.
func write(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if dest, ok := strings.CutPrefix(content, "->"); ok {
			if err := os.Symlink(dest, p); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func pkg(name, version string) string {
	return `{"name":"` + name + `","version":"` + version + `"}`
}

func check(t *testing.T, dir, lockfile string, modules ...string) Report {
	t.Helper()
	if len(modules) == 0 {
		modules = []string{"node_modules"}
	}
	r, err := Check(Options{Lockfile: filepath.Join(dir, lockfile), Source: dir, Target: dir, Modules: modules, Exclude: []string{".cache"}})
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	return r
}

func wantProblems(t *testing.T, r Report, want ...string) {
	t.Helper()
	if want == nil {
		want = []string{}
	}
	if !reflect.DeepEqual(r.Problems, want) {
		t.Fatalf("problems = %q, want %q", r.Problems, want)
	}
}

func TestNpmLockfileTree(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, map[string]string{
		"package.json": `{"name":"app","dependencies":{"left-pad":"^1"}}`,
		"package-lock.json": `{"lockfileVersion":3,"packages":{
			"":{"name":"app"},
			"packages/ws":{"name":"ws-pkg","version":"1.0.0"},
			"node_modules/ws-pkg":{"resolved":"packages/ws","link":true},
			"node_modules/left-pad":{"version":"1.3.0"},
			"node_modules/@s/nested":{"version":"2.0.0"},
			"node_modules/left-pad/node_modules/dep":{"version":"0.1.0"},
			"node_modules/fsevents":{"version":"2.3.3","optional":true},
			"node_modules/bundler":{"version":"1.0.0"},
			"node_modules/bundler/node_modules/inside":{"version":"9.9.9","inBundle":true},
			"node_modules/alias":{"name":"real-pkg","version":"4.0.0"}}}`,
		"packages/ws/package.json":                              pkg("ws-pkg", "1.0.0"),
		"node_modules/ws-pkg":                                   "->../packages/ws",
		"node_modules/left-pad/package.json":                    pkg("left-pad", "1.3.0"),
		"node_modules/@s/nested/package.json":                   pkg("@s/nested", "2.0.0"),
		"node_modules/left-pad/node_modules/dep/package.json":   pkg("dep", "0.1.0"),
		"node_modules/bundler/package.json":                     `{"name":"bundler","version":"1.0.0","bundleDependencies":["inside"]}`,
		"node_modules/bundler/node_modules/inside/package.json": pkg("inside", "0.0.0-not-locked"),
		"node_modules/alias/package.json":                       pkg("real-pkg", "4.0.0"),
		"node_modules/.bin/pad":                                 "->../left-pad/index.js",
		"node_modules/.package-lock.json":                       `{}`,
		"node_modules/.cache/babel/x.json":                      `{}`,
	})
	r := check(t, dir, "package-lock.json")
	wantProblems(t, r)
	if r.Format != "npm" || r.Installed != 5 {
		t.Fatalf("format %q installed %d, want npm 5", r.Format, r.Installed)
	}

	// A stale tree: a version the lockfile no longer pins, and a package
	// the lockfile pins that is not there.
	write(t, dir, map[string]string{"node_modules/@s/nested/package.json": pkg("@s/nested", "1.0.0")})
	wantProblems(t, check(t, dir, "package-lock.json"), "missing @s/nested@2.0.0", "not in the lockfile: @s/nested@1.0.0")
}

